import pytest

from brain.bank import BankError, Selection
from brain.render.latex import date_range, render, tex


@pytest.mark.parametrize("text, expected", [
    ("R&D", r"R\&D"),
    ("100% uptime", r"100\% uptime"),
    ("10 %", r"10\,\%"),                       # French thin space
    ("snake_case", r"snake\_case"),
    ("$5 and #1", r"\$5 and \#1"),
    ("{x}", r"\{x\}"),
    ("a~b", r"a$\sim$b"),
    ("a^2", r"a\^{}2"),
    ("back\\slash", r"back\textbackslash{}slash"),
    ("CPU vs. GPU", r"CPU vs.\ GPU"),
    ("Élève, déjà", "Élève, déjà"),           # accents pass through (LuaLaTeX)
])
def test_tex_escapes_special_characters(text, expected):
    assert tex(text) == expected


def test_tex_markdown_bold_and_code():
    assert tex("**aTaS:** a `test_gen` tool") == r"\textbf{aTaS:} a \texttt{test\_gen} tool"
    assert tex("**R&D**") == r"\textbf{R\&D}"
    assert tex("a ** b") == "a ** b"           # lone stars are kept as text


@pytest.mark.parametrize("meta, lang, expected", [
    ({"start": "2025-10", "end": "2026-09"}, "en", r"Oct.\ 2025 -- Sept.\ 2026"),
    ({"start": "2024-04", "end": "2024-08"}, "en", r"Apr.\ -- Aug.\ 2024"),
    ({"start": "2024-04", "end": "2024-04"}, "en", r"Apr.\ 2024"),
    ({"start": "2025-10", "end": "present"}, "en", r"Oct.\ 2025 -- Present"),
    ({"start": "2025-10", "end": "present"}, "fr", r"Oct.\ 2025 -- aujourd'hui"),
    ({"start": "2024-06", "end": "2024-08"}, "fr", "Juin -- août 2024"),
    ({"start": 2023, "end": 2025}, "en", "2023 -- 2025"),
    ({}, "en", ""),
])
def test_date_range(meta, lang, expected):
    assert date_range(meta, lang) == expected


def test_bad_date_is_reported():
    with pytest.raises(BankError):
        date_range({"start": "Oct 2025"}, "en")


@pytest.mark.parametrize("lang", ["en", "fr"])
def test_default_selection_renders(bank, default_sel, lang):
    out = render(bank, default_sel, lang)
    assert out.startswith("% Generated by Ninurta")
    assert out.count(r"\begin{document}") == 1 and out.rstrip().endswith(r"\end{document}")
    assert out.count("{") == out.count("}") + out.count(r"\{") - out.count(r"\}")


def test_render_rejects_unknown_ids(bank):
    with pytest.raises(BankError, match="no bank entry"):
        render(bank, Selection.from_dict({"sections": ["experience"], "experience": ["nope"]}), "en")
    eid = next(iter(bank["experience"]))
    with pytest.raises(BankError, match="no bullet"):
        render(bank, Selection.from_dict({"sections": ["experience"],
                                          "experience": [{"id": eid, "bullets": ["nope"]}]}), "en")


def test_reworded_bullet_and_overrides(bank):
    eid, entry = next(iter(bank["experience"].items()))
    bid = next(iter(entry.bullets))
    sel = Selection.from_dict({"sections": ["experience"], "experience": [
        {"id": eid, "title": {"en": "Custom Title", "fr": "Titre perso"},
         "bullets": [{"id": bid, "en": "Reworded & shorter"}]}]})
    assert "Custom Title" in render(bank, sel, "en") and "Titre perso" in render(bank, sel, "fr")
    assert r"Reworded \& shorter" in render(bank, sel, "en")
    assert entry.bullets[bid].text["fr"].split()[0] in render(bank, sel, "fr")   # no fr: bank text
